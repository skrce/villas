CREATE TABLE IF NOT EXISTS apartments (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL DEFAULT '${propertyId}',
    capacity INT NOT NULL CHECK (capacity > 0),
    orientation VARCHAR(200),
    view VARCHAR(200),
    regular_price INT CHECK (regular_price >= 0),
    top_season_price INT CHECK (top_season_price >= 0),
    CONSTRAINT apartment_property_id UNIQUE (property_id, id)
);

CREATE TABLE IF NOT EXISTS customers (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL DEFAULT '${propertyId}',
    first_name VARCHAR(200) NOT NULL,
    last_name VARCHAR(200) NOT NULL,
    phone VARCHAR(200) NOT NULL,
    address VARCHAR(200) NOT NULL,
    CONSTRAINT customer_property_id UNIQUE (property_id, id)
);

CREATE TABLE IF NOT EXISTS reservations (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL DEFAULT '${propertyId}',
    customer_id INT NOT NULL,
    room_id INT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT valid_stay CHECK (
        start_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date > start_date
    ),
    CONSTRAINT reservation_customer FOREIGN KEY (property_id, customer_id) REFERENCES customers (property_id, id),
    CONSTRAINT reservation_room FOREIGN KEY (property_id, room_id) REFERENCES apartments (property_id, id),
    CONSTRAINT reservation_property_id UNIQUE (property_id, id)
);
CREATE INDEX IF NOT EXISTS room_overlap ON reservations (property_id, room_id, start_date, end_date);
