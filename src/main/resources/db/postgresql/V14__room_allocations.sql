UPDATE reservations SET room_from_date=start_date WHERE room_from_date IS NULL;
ALTER TABLE inventory_events ADD COLUMN IF NOT EXISTS room_from_date DATE NULL;

CREATE TABLE IF NOT EXISTS reservation_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    reservation_id INT NOT NULL,
    room_id INT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT allocation_dates CHECK (
        start_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date > start_date
    ),
    CONSTRAINT allocation_reservation FOREIGN KEY(property_id,reservation_id) REFERENCES reservations(property_id,id),
    CONSTRAINT allocation_room FOREIGN KEY(property_id,room_id) REFERENCES apartments(property_id,id),
    CONSTRAINT allocation_start UNIQUE (property_id,reservation_id,start_date)
);
CREATE INDEX IF NOT EXISTS allocation_room_window ON reservation_allocations (property_id,room_id,start_date,end_date);
CREATE INDEX IF NOT EXISTS allocation_history ON reservation_allocations (property_id,reservation_id,id);

INSERT INTO reservation_allocations(property_id,reservation_id,room_id,start_date,end_date)
    SELECT r.property_id,r.id,r.room_id,r.start_date,r.end_date FROM reservations r
    WHERE NOT EXISTS(SELECT 1 FROM reservation_allocations a WHERE a.property_id=r.property_id AND a.reservation_id=r.id) ON CONFLICT DO NOTHING;
