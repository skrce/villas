CREATE TABLE IF NOT EXISTS staff_accounts (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    issuer VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(issuer) > 0),
    subject VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(subject) > 0),
    email VARCHAR(254) NOT NULL CHECK (CHAR_LENGTH(email) > 0 AND email = LOWER(TRIM(email))),
    role VARCHAR(16) NOT NULL DEFAULT 'OWNER' CHECK (role = 'OWNER'),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    security_version BIGINT NOT NULL DEFAULT 0 CHECK (security_version >= 0),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT staff_identity UNIQUE (property_id, issuer, subject),
    CONSTRAINT staff_email UNIQUE (property_id, email),
    CONSTRAINT staff_property_id UNIQUE (property_id, id)
);
CREATE INDEX IF NOT EXISTS active_owners ON staff_accounts (property_id, active, role);

CREATE TABLE IF NOT EXISTS staff_invitations (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    email VARCHAR(254) NOT NULL CHECK (CHAR_LENGTH(email) > 0 AND email = LOWER(TRIM(email))),
    state VARCHAR(16) NOT NULL CHECK (state IN ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED')),
    created_by VARCHAR(36),
    accepted_by VARCHAR(36),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT invitation_expiry CHECK (expires_at > created_at),
    CONSTRAINT invitation_creator FOREIGN KEY (property_id, created_by) REFERENCES staff_accounts (property_id, id),
    CONSTRAINT invitation_recipient FOREIGN KEY (property_id, accepted_by) REFERENCES staff_accounts (property_id, id)
);
CREATE INDEX IF NOT EXISTS pending_invitation ON staff_invitations (property_id, email, state, expires_at);

CREATE TABLE IF NOT EXISTS staff_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    actor_id VARCHAR(36),
    kind VARCHAR(32) NOT NULL,
    subject_type VARCHAR(16) NOT NULL CHECK (subject_type IN ('STAFF', 'INVITATION')),
    subject_id VARCHAR(36) NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT staff_event_actor FOREIGN KEY (property_id, actor_id) REFERENCES staff_accounts (property_id, id)
);
CREATE INDEX IF NOT EXISTS staff_history ON staff_events (property_id, id);
