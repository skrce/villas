ALTER TABLE reservations
    ADD COLUMN IF NOT EXISTS stay_phase VARCHAR(16) NOT NULL DEFAULT 'CONFIRMED',
    ADD COLUMN IF NOT EXISTS checked_in_at TIMESTAMP(6) WITH TIME ZONE NULL,
    ADD COLUMN IF NOT EXISTS checked_out_at TIMESTAMP(6) WITH TIME ZONE NULL;

UPDATE reservations SET stay_phase='CANCELLED'
    WHERE status='CANCELLED' AND stay_phase='CONFIRMED';

ALTER TABLE reservations DROP CONSTRAINT IF EXISTS stay_phase_status;
ALTER TABLE reservations ADD CONSTRAINT stay_phase_status CHECK (
    (status='ACTIVE' AND stay_phase IN ('CONFIRMED','CHECKED_IN','CHECKED_OUT'))
    OR (status='CANCELLED' AND stay_phase IN ('CANCELLED','NO_SHOW'))
);
ALTER TABLE reservations DROP CONSTRAINT IF EXISTS stay_phase_times;
ALTER TABLE reservations ADD CONSTRAINT stay_phase_times CHECK (
    (stay_phase IN ('CONFIRMED','CANCELLED','NO_SHOW') AND checked_in_at IS NULL AND checked_out_at IS NULL)
    OR (stay_phase='CHECKED_IN' AND checked_in_at IS NOT NULL AND checked_out_at IS NULL)
    OR (stay_phase='CHECKED_OUT' AND checked_in_at IS NOT NULL AND checked_out_at IS NOT NULL AND checked_out_at>=checked_in_at)
);
CREATE INDEX IF NOT EXISTS physical_room_occupancy ON reservations(property_id,room_id,stay_phase);
CREATE INDEX IF NOT EXISTS stay_arrivals ON reservations(property_id,stay_phase,start_date,id);
CREATE INDEX IF NOT EXISTS stay_departures ON reservations(property_id,stay_phase,end_date,id);

ALTER TABLE inventory_events
    ADD COLUMN IF NOT EXISTS reason VARCHAR(500) NULL,
    ADD COLUMN IF NOT EXISTS stay_phase VARCHAR(16) NULL,
    ADD COLUMN IF NOT EXISTS checked_in_at TIMESTAMP(6) WITH TIME ZONE NULL,
    ADD COLUMN IF NOT EXISTS checked_out_at TIMESTAMP(6) WITH TIME ZONE NULL;

CREATE TABLE IF NOT EXISTS room_readiness (
    room_id INT NOT NULL PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL DEFAULT 'DIRTY' CHECK (state IN ('DIRTY','IN_PROGRESS','INSPECTION','CLEAN')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version BETWEEN 0 AND 9007199254740991),
    changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT readiness_room FOREIGN KEY (property_id,room_id) REFERENCES apartments(property_id,id),
    CONSTRAINT property_readiness UNIQUE (property_id,room_id)
);

INSERT INTO room_readiness (room_id,property_id,state,version,changed_at)
    SELECT id,property_id,'DIRTY',0,CURRENT_TIMESTAMP(6) FROM apartments ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS readiness_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    room_id INT NOT NULL,
    actor_id VARCHAR(36) NOT NULL,
    operation_key VARCHAR(36) NOT NULL,
    resource_version BIGINT NOT NULL CHECK (resource_version BETWEEN 0 AND 9007199254740991),
    previous_state VARCHAR(16) NOT NULL CHECK (previous_state IN ('DIRTY','IN_PROGRESS','INSPECTION','CLEAN')),
    state VARCHAR(16) NOT NULL CHECK (state IN ('DIRTY','IN_PROGRESS','INSPECTION','CLEAN')),
    reason VARCHAR(500) NULL,
    reservation_id INT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT readiness_event_room FOREIGN KEY (property_id,room_id) REFERENCES apartments(property_id,id),
    CONSTRAINT readiness_event_actor FOREIGN KEY (actor_id) REFERENCES staff_accounts(id),
    CONSTRAINT readiness_event_reservation FOREIGN KEY (property_id,reservation_id) REFERENCES reservations(property_id,id),
    CONSTRAINT readiness_event_version UNIQUE (property_id,room_id,resource_version)
);
CREATE INDEX IF NOT EXISTS readiness_history ON readiness_events (property_id,room_id,id);
