CREATE TABLE IF NOT EXISTS maintenance_blocks (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL DEFAULT '${propertyId}',
    room_id INT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR(200) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CANCELLED')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT block_valid_stay CHECK (
        start_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date BETWEEN DATE '1000-01-01' AND DATE '9999-12-31'
        AND end_date > start_date
    ),
    CONSTRAINT block_room FOREIGN KEY (property_id, room_id) REFERENCES apartments (property_id, id),
    CONSTRAINT block_property_id UNIQUE (property_id, id)
);
CREATE INDEX IF NOT EXISTS block_overlap ON maintenance_blocks (property_id, room_id, status, start_date, end_date);

CREATE TABLE IF NOT EXISTS inventory_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    actor_id VARCHAR(64) NOT NULL,
    operation_kind VARCHAR(32) NOT NULL,
    operation_key VARCHAR(36) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    result_json TEXT CHECK (result_json IS NULL OR result_json IS JSON),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT operation_identity UNIQUE (property_id, actor_id, operation_kind, operation_key)
);

CREATE TABLE IF NOT EXISTS inventory_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id VARCHAR(64) NOT NULL,
    actor_id VARCHAR(64) NOT NULL,
    operation_key VARCHAR(36) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    reservation_id INT,
    maintenance_block_id INT,
    resource_version BIGINT NOT NULL CHECK (resource_version >= 0),
    room_id INT NOT NULL,
    previous_room_id INT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    guest_count INT,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT event_subject CHECK ((reservation_id IS NOT NULL AND maintenance_block_id IS NULL) OR (reservation_id IS NULL AND maintenance_block_id IS NOT NULL)),
    CONSTRAINT event_reservation FOREIGN KEY (property_id, reservation_id) REFERENCES reservations (property_id, id),
    CONSTRAINT event_block FOREIGN KEY (property_id, maintenance_block_id) REFERENCES maintenance_blocks (property_id, id),
    CONSTRAINT event_room FOREIGN KEY (property_id, room_id) REFERENCES apartments (property_id, id),
    CONSTRAINT event_previous_room FOREIGN KEY (property_id, previous_room_id) REFERENCES apartments (property_id, id),
    CONSTRAINT reservation_event_version UNIQUE (property_id, reservation_id, resource_version),
    CONSTRAINT block_event_version UNIQUE (property_id, maintenance_block_id, resource_version)
);
